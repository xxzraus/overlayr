const THEME_MAP = new Map(THEMES.map((t) => [t.id, t]));

function getTheme(id) {
  return THEME_MAP.get(id) || THEME_MAP.get('aurora');
}

/** CSS custom properties payload for a theme. */
function themeVars(theme) {
  const radius = Number(theme.radius ?? 16);
  return {
    '--bg': theme.bg,
    '--bg2': theme.bg2,
    '--text': theme.text,
    '--accent': theme.accent,
    '--accent2': theme.accent2,
    '--aura': theme.aura,
    '--contrast': String(theme.contrast ?? 1),
    '--aura-strength': String(theme.glow ?? 1),
    '--grad-angle': `${Number(theme.angle ?? 180)}deg`,
    '--radius': `${radius}px`,
    '--radius-lg': `${radius + 6}px`,
    '--radius-sm': `${Math.max(6, radius - 6)}px`,
    '--mode': theme.dark ? 'dark' : 'light',
  };
}

/** Windows accent hex, used for the system accent/wallpaper. */
function themeAccentHex(theme) {
  return theme.accent;
}

module.exports = { THEMES, THEME_MAP, getTheme, themeVars, themeAccentHex };
